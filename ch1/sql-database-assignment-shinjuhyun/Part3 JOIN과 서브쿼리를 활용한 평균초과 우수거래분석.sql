-- 여기에 문제 1의 SQL을 작성하세요.

select s.sale_id, s.sale_date, p.product_name, c.customer_name, c.customer_type, c.customer_region, s.sales_type, s.quantity, s.sale_amount, s.payment_status

	from sales s --1
join products p
	on s.product_id = p.product_id --2

join customers c --1
	 on s.customer_id = c.customer_id --2
	 
where s.sale_date >= '2025-04-01' and s.sale_date < '2025-07-01' --3
	and s.sales_type != '반품'
	and s.sale_amount > ( --4
		select avg(sale_amount) --5
			from sales s
			where sale_date >= '2025-04-01' and sale_date < '2025-07-01'
				and sales_type != '반품')
order by s.sale_amount desc, s.sale_date desc; --7,8
	


