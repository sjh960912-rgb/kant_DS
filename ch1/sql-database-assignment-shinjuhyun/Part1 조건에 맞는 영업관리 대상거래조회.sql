/* ============================================================================
문제 1. 조건에 맞는 영업관리 대상 거래 조회
===============================================================================

[업무 요청]
영업관리팀이 우선 점검할 2025년 2분기 판매 거래를 조회하세요.

[필수 요구사항]
1. sales 테이블을 사용하세요.
2. 다음 컬럼만 조회하세요.
   - sale_id
   - sale_date
   - product_id
   - sales_dept_id
   - customer_id
   - sales_type
   - sale_amount
   - payment_status
3. 판매일자가 2025년 4월 1일 이상, 2025년 7월 1일 미만인 거래만
   조회하세요.
4. sales_type이 '반품'인 거래는 제외하세요.
5. sale_amount가 500000 이상인 거래만 조회하세요.
6. sale_amount를 기준으로 내림차순 정렬하세요.
7. sale_amount가 같으면 sale_date를 기준으로 내림차순 정렬하세요.

[유의사항]
- 요구사항에 없는 컬럼은 조회하지 않습니다.
- 날짜 조건, 판매 유형 조건과 판매금액 조건을 모두 만족해야 합니다.
- 결과 해석은 작성하지 않아도 됩니다.
===============================================================================
*/

-- 여기에 문제 1의 SQL을 작성하세요.


select sale_id, sale_date, product_id, sales_dept_id, customer_id, sales_type, sale_amount, payment_status
from sales
where sale_date >= '2025-04-01' and sale_date < '2025-07-01'
	  and sales_type != '반품'
	  and sale_amount >= 500000
order by sale_amount desc, sale_date desc;


